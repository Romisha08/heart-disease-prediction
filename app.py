import streamlit as st
import pandas as pd
import joblib


# --------------------------------------------------
# Page configuration
# --------------------------------------------------

st.set_page_config(
    page_title="Heart Disease Prediction",
    page_icon="❤️",
    layout="centered"
)


# --------------------------------------------------
# Load trained model
# --------------------------------------------------

model = joblib.load(
    "artifacts/heart_disease_pipeline.joblib"
)


# --------------------------------------------------
# Title
# --------------------------------------------------

st.title("❤️ Heart Disease Prediction System")

st.write(
    """
    Enter the patient's clinical information below to
    generate a machine learning prediction.
    """
)

st.warning(
    "This application is for educational purposes only "
    "and is not a medical diagnosis."
)


# --------------------------------------------------
# Patient information
# --------------------------------------------------

st.subheader("Patient Information")

age = st.number_input(
    "Age",
    min_value=1,
    max_value=120,
    value=50
)

sex = st.selectbox(
    "Sex",
    options=[0, 1],
    format_func=lambda x:
        "Female" if x == 0 else "Male"
)

cp = st.selectbox(
    "Chest Pain Type",
    options=[1, 2, 3, 4],
    format_func=lambda x: {
        1: "Typical Angina",
        2: "Atypical Angina",
        3: "Non-anginal Pain",
        4: "Asymptomatic"
    }[x]
)

trestbps = st.number_input(
    "Resting Blood Pressure (mm Hg)",
    min_value=50,
    max_value=250,
    value=120
)

chol = st.number_input(
    "Serum Cholesterol (mg/dl)",
    min_value=50,
    max_value=600,
    value=200
)

fbs = st.selectbox(
    "Fasting Blood Sugar > 120 mg/dl",
    options=[0, 1],
    format_func=lambda x:
        "No" if x == 0 else "Yes"
)

restecg = st.selectbox(
    "Resting ECG",
    options=[0, 1, 2]
)

thalch = st.number_input(
    "Maximum Heart Rate",
    min_value=50,
    max_value=250,
    value=150
)

exang = st.selectbox(
    "Exercise Induced Angina",
    options=[0, 1],
    format_func=lambda x:
        "No" if x == 0 else "Yes"
)

oldpeak = st.number_input(
    "ST Depression (Oldpeak)",
    min_value=0.0,
    max_value=10.0,
    value=1.0,
    step=0.1
)

slope = st.selectbox(
    "Slope",
    options=[1, 2, 3]
)

ca = st.selectbox(
    "Number of Major Vessels",
    options=[0, 1, 2, 3]
)

thal = st.selectbox(
    "Thalassemia",
    options=[3, 6, 7],
    format_func=lambda x: {
        3: "Normal",
        6: "Fixed Defect",
        7: "Reversible Defect"
    }[x]
)


# --------------------------------------------------
# Create input dataframe
# --------------------------------------------------

input_data = pd.DataFrame({
    "age": [age],
    "sex": [sex],
    "cp": [cp],
    "trestbps": [trestbps],
    "chol": [chol],
    "fbs": [fbs],
    "restecg": [restecg],
    "thalch": [thalch],
    "exang": [exang],
    "oldpeak": [oldpeak],
    "slope": [slope],
    "ca": [ca],
    "thal": [thal]
})


# --------------------------------------------------
# Prediction
# --------------------------------------------------

if st.button("🔍 Predict Heart Disease"):

    prediction = model.predict(input_data)[0]

    probability = model.predict_proba(
        input_data
    )[0][1]

    st.subheader("Prediction Result")

    if prediction == 1:

        st.error(
            "⚠️ Potential presence of heart disease"
        )

    else:

        st.success(
            "✅ No heart disease detected by the model"
        )

    st.metric(
        "Predicted Probability",
        f"{probability * 100:.2f}%"
    )

    st.caption(
        "This prediction is generated by a machine learning "
        "model and should not be used as medical advice."
    )